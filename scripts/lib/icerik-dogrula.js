/**
 * 01-icerik-uret icerigi urettikten SONRA tek Gemini cagrisi ile her soruyu kontrol eder.
 * Sonuc her sorunun altina `dogrulama` alani olarak yazilir:
 *   { durum: "temiz" }
 *   { durum: "supheli", kontroller: ["gorsel", ...], gerekce: "...", oneri: "..." }
 * Soru metni / sik / prompt DEGISTIRILMEZ. Karar kullanicida (Onay 2 formunda gorunur).
 * Dogrulama patlarsa uretim DURMAZ: sorular dogrulama alani olmadan devam eder.
 */

import { GoogleGenerativeAI } from "@google/generative-ai";

export const KONTROL_ADLARI = ["olgu", "gorsel", "sik"];
const MAX_METIN = 240; // issue govdesi 65KB limitine yakin -> gerekce/oneri kisa tutulur
const kisalt = (s) => String(s || "").replace(/\s+/g, " ").trim().substring(0, MAX_METIN);
const yildizsiz = (s) => String(s || "").replace(/\*\*/g, "");

// Gemini'ye giden kompakt soru ozeti (url, ses metni vb. gonderilmez)
function soruOzeti(q, i) {
  if (q.question_type === "would_you_rather") {
    const v = q.visible_option || {}, s = q.surprise_option || {};
    return {
      index: i,
      type: "would_you_rather",
      question_text: yildizsiz(q.question_text),
      visible_option: { label: v.label || "", image_prompt: v.image_prompt || "" },
      surprise_option: {
        label: s.label || "",
        outcome: s.surprise_outcome || "",
        image_prompt: s.surprise_image_prompt || "",
      },
      reveal_text: q.reveal_audio_text || "",
    };
  }
  const opts = q.options || [];
  return {
    index: i,
    type: "multiple_choice",
    question_text: yildizsiz(q.question_text),
    options: opts.map((o, j) => `${["A", "B", "C"][j]}: ${o}`),
    correct_answer: `${["A", "B", "C"][q.correct_answer] || "?"}: ${opts[q.correct_answer] ?? ""}`,
    fun_fact: yildizsiz(q.fun_fact),
    question_image_prompt: q.image_prompt || "",
    fun_fact_image_prompt: q.fun_fact_image_prompt || "",
  };
}

export function dogrulamaPrompt(konu, questions) {
  const ozet = questions.map(soruOzeti);
  return `You are a strict fact-checker and quality reviewer for "GeniMini Tests", an EDUCATIONAL quiz YouTube channel for kids ages 4-12.
Wrong or misleading information is a serious problem (reputation + YouTube "misleadingly educational" policy).
Topic: "${konu}"

Review EVERY question below with THREE independent checks. Be strict: when in doubt, FLAG. Do NOT rewrite the quiz, only report.

CHECK 1 — "olgu" (factual accuracy)
- Is the marked correct answer actually correct? Is any other option ALSO correct?
- Is the fun fact true? Check numbers, dates, names, records, origins with special care.
- Is the question's PREMISE true? (e.g. "Which flying dinosaur..." when pterosaurs are NOT dinosaurs → flag)
- Is the claim disputed among experts? (e.g. "croissants are from France" is disputed — Austrian kipferl origin → flag; "pizza is from Italy" is fine)
- Internal contradiction between question, answer and fun fact → flag.

CHECK 2 — "gorsel" (image ↔ question match) — THE MOST IMPORTANT CHECK
The question image is generated by a text-to-image model from question_image_prompt and is shown WHILE the question is asked.
Image models do NOT reliably know species / landmark / object names: they draw from the VISUAL WORDS in the prompt.
- Identify the distinguishing feature the question asks about or depends on (a back sail, horns, wings, stripes, colour, shape, size, number of legs, a landmark's shape...).
- The question_image_prompt MUST describe that feature EXPLICITLY in visual words.
- If the prompt only NAMES the subject (e.g. "Spinosaurus standing in a river") and does not describe the asked feature (e.g. "large tall sail on its back"), FLAG it — the child cannot find the answer from the image.
- For "Which X is this?" questions: the prompt must describe the correct answer's identifying visual features, otherwise the model may draw a generic look-alike → FLAG.
- The prompt must not depict a WRONG option instead, and must not contradict the question.
- fun_fact_image_prompt must match the fun fact; if it depicts something false or unrelated → FLAG.
- For would_you_rather: each image_prompt must clearly show its own option / outcome.

CHECK 3 — "sik" (option clarity, multiple_choice only; would_you_rather → always ok)
- Can more than one option be defended as correct?
- Are wrong options too close / ambiguous, or obviously silly in a way that breaks the quiz?
- Are option texts written consistently (same naming style, same kind of thing, similar length)?

OUTPUT: JSON only, exactly this shape, one entry per question, same index values:
{"results":[{"index":0,
  "olgu":{"ok":true,"reason":""},
  "gorsel":{"ok":false,"reason":"<one sentence>"},
  "sik":{"ok":true,"reason":""},
  "suggestion":"<what would fix it, empty if nothing>"}]}
Rules: "reason" is ONE short sentence, written in TURKISH, only when ok=false (empty string when ok=true).
"suggestion" is written in TURKISH, short, empty when everything is ok. Image prompt fixes may quote English prompt words.

QUESTIONS:
${JSON.stringify(ozet, null, 1)}`;
}

// Gemini yanitini soru basina dogrulama kaydina cevir
export function sonucuKayitlaraCevir(results, n) {
  const byIdx = new Map((results || []).map(r => [Number(r.index), r]));
  return Array.from({ length: n }, (_, i) => {
    const r = byIdx.get(i);
    if (!r) return null; // Gemini bu soruyu atladi -> kayit yok (belirsiz), temiz SAYILMAZ
    const kalan = KONTROL_ADLARI.filter(k => r[k] && r[k].ok === false);
    if (!kalan.length) return { durum: "temiz" };
    const kayit = {
      durum: "supheli",
      kontroller: kalan,
      // tek kontrol -> onek yok (form/Telegram zaten kontrol adini gosteriyor)
      gerekce: kisalt(kalan.length === 1 ? (r[kalan[0]].reason || "-") : kalan.map(k => `${k}: ${r[k].reason || "-"}`).join(" | ")),
    };
    if (r.suggestion && String(r.suggestion).trim()) kayit.oneri = kisalt(r.suggestion);
    return kayit;
  });
}

/**
 * Tek Gemini cagrisi. Hata olursa sadece bir kez diger key ile tekrar dener.
 * Donus: { kayitlar: [dogrulama|null, ...], hata: null | "mesaj" }
 */
export async function icerikDogrula(konu, questions, keys, modelAdi = "gemini-2.5-flash") {
  const anahtarlar = (keys || []).filter(Boolean);
  if (!anahtarlar.length) return { kayitlar: questions.map(() => null), hata: "GEMINI key yok" };
  const prompt = dogrulamaPrompt(konu, questions);
  let sonHata = null;
  for (const key of anahtarlar.slice(0, 2)) {
    try {
      const model = new GoogleGenerativeAI(key).getGenerativeModel({
        model: modelAdi,
        generationConfig: { responseMimeType: "application/json", temperature: 0.2, maxOutputTokens: 32768 },
      });
      const result = await model.generateContent(prompt);
      const json = JSON.parse(result.response.text().trim());
      if (!Array.isArray(json.results)) throw new Error("results dizisi yok");
      return { kayitlar: sonucuKayitlaraCevir(json.results, questions.length), hata: null };
    } catch (e) {
      sonHata = e.message;
      console.warn(`⚠ Dogrulama denemesi basarisiz: ${e.message.substring(0, 200)}`);
    }
  }
  return { kayitlar: questions.map(() => null), hata: sonHata };
}

// Kayitlari sorulara yaz (sadece `dogrulama` alani eklenir, baska alana DOKUNULMAZ)
export function dogrulamaUygula(questions, kayitlar) {
  questions.forEach((q, i) => {
    if (kayitlar[i]) q.dogrulama = kayitlar[i];
  });
}

// Telegram satiri: "Dogrulama: 15 soru, 3 supheli (olgu 1, gorsel 2)" / "Dogrulama: 15 soru, hepsi temiz"
export function dogrulamaOzetSatiri(questions, hata = null) {
  const n = questions.length;
  // Telegram Markdown: hata metnindeki _ * [ ` mesaji 400'e dusurur -> temizle
  if (hata) return `Dogrulama: calismadi (${String(hata).replace(/[_*[\]`]/g, " ").substring(0, 80)})`;
  const supheli = questions.filter(q => q.dogrulama?.durum === "supheli");
  const kayitsiz = questions.filter(q => !q.dogrulama).length;
  const ek = kayitsiz ? `, ${kayitsiz} kontrol edilemedi` : "";
  if (!supheli.length) return `Dogrulama: ${n} soru, ${kayitsiz ? "supheli yok" : "hepsi temiz"}${ek}`;
  const sayac = KONTROL_ADLARI
    .map(k => [k, supheli.filter(q => (q.dogrulama.kontroller || []).includes(k)).length])
    .filter(([, c]) => c > 0)
    .map(([k, c]) => `${k} ${c}`)
    .join(", ");
  return `Dogrulama: ${n} soru, ${supheli.length} supheli (${sayac})${ek}`;
}
